#!/usr/bin/env python3
"""Square frame SVGs for the laland Plasma style.

Element ids follow Breeze's own files (/usr/share/plasma/desktoptheme/default/...): each frame is
<prefix>topleft, <prefix>top, ... <prefix>center, optional <prefix>hint-*-margin; colors come from
ColorScheme-* classes, which Plasma recolors from the active color scheme (ButtonFocus = focus pink).
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "templates" / "plasma"
STYLE = """  <defs><style id="current-color-scheme" type="text/css">
    .ColorScheme-Background { color:#1b2236; }
    .ColorScheme-ViewBackground { color:#141b2e; }
    .ColorScheme-Text { color:#e3e6ef; }
    .ColorScheme-ButtonFocus { color:#ff93dd; }
  </style></defs>"""

class Sheet:
    def __init__(self):
        self.parts, self.x = [], 0

    def frame(self, prefix, border, b, center=None, center_opacity=1.0, border_opacity=1.0, margin=None):
        """border/center: ColorScheme class name or None (transparent)."""
        c, x0 = 4, self.x
        s = b + c
        def rect(name, x, y, w, h, cls, op):
            fill = f'fill:currentColor;fill-opacity:{op}' if cls else 'fill:#000000;fill-opacity:0'
            klass = f' class="ColorScheme-{cls}"' if cls else ''
            self.parts.append(f'  <rect id="{prefix}{name}"{klass} x="{x0 + x}" y="{y}" width="{w}" height="{h}" style="{fill}"/>')
        for name, x, y, w, h in [("topleft", 0, 0, b, b), ("top", b, 0, c, b), ("topright", s, 0, b, b),
                                 ("left", 0, b, b, c), ("right", s, b, b, c),
                                 ("bottomleft", 0, s, b, b), ("bottom", b, s, c, b), ("bottomright", s, s, b, b)]:
            rect(name, x, y, w, h, border, border_opacity)
        rect("center", b, b, c, c, center, center_opacity)
        if margin is not None:
            for i, side in enumerate(("top", "bottom", "left", "right")):
                self.parts.append(f'  <rect id="{prefix}hint-{side}-margin" x="{x0 + i * (margin + 1)}" y="{s + 4}" '
                                  f'width="{margin}" height="{margin}" style="fill:#ff00ff;fill-opacity:0"/>')
        self.x += s + 2 * b + 20

    def write(self, rel, extra=()):
        w = self.x + 20
        body = "\n".join([f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="60" viewBox="0 0 {w} 60">',
                          STYLE, *self.parts, *extra, "</svg>", ""])
        path = OUT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('<?xml version="1.0" encoding="UTF-8"?>\n<!-- laland square frame. Generated by scripts/plasma_svgs.py -->\n' + body)
        return path

def main():
    # dialogs: KRunner and other popups. Navy inside, 2px pink border, no shadow.
    d = Sheet()
    d.frame("", "ButtonFocus", 2, "Background", margin=6)
    d.frame("mask-", None, 2, None)
    print(d.write("dialogs/background.svg"))

    # line edits (KRunner search field): darker navy box with a faint edge; no pink (KRunner's field is
    # always focused, so a pink focus border was always on).
    le = Sheet()
    le.frame("base-", "Text", 1, "ViewBackground", border_opacity=0.15, margin=5)
    le.frame("hover-", "Text", 1, None, border_opacity=0.15, margin=5)
    le.frame("focus-", "Text", 1, None, border_opacity=0.25, margin=5)
    le.frame("focusframe-", "Text", 1, None, border_opacity=0.25, margin=5)
    print(le.write("widgets/lineedit.svg", ['  <rect id="hint-focus-over-base" x="0" y="55" width="1" height="1" style="fill-opacity:0"/>']))

    # list items: no fill, 2px pink border (like Sidebery's tab). KRunner draws its current result with
    # the hover- frame, not selected-, so both get the pink border.
    vi = Sheet()
    vi.frame("normal-", None, 2, None)
    vi.frame("hover-", "ButtonFocus", 2, None)
    vi.frame("selected-", "ButtonFocus", 2, None)
    print(vi.write("widgets/viewitem.svg"))

if __name__ == "__main__":
    main()
