#!/usr/bin/env bash
# Install "laland" Plasma style: Klassy Dark's shapes with no colors file, so panels and
# Plasma widgets follow the active color scheme (LalandDark/LalandLight), the way Breeze's
# "default" style does (it ships no colors file; breeze-dark and klassy-dark do).
set -euo pipefail
src=/usr/share/plasma/desktoptheme/klassy-dark
dst="$HOME/.local/share/plasma/desktoptheme/laland"
rm -rf "$dst"
mkdir -p "$(dirname "$dst")"
cp -r "$src" "$dst"
rm -f "$dst/colors"
sed -i 's/^FallbackTheme=.*/FallbackTheme=default/' "$dst/plasmarc"
python3 - "$dst/metadata.json" <<'PY'
import json, sys
p = sys.argv[1]
d = json.load(open(p))
k = d["KPlugin"]
k = {key: v for key, v in k.items() if not key.startswith(("Name[", "Description["))}
k.update(Id="laland", Name="laland", Description="Klassy Dark shapes, colors from the active scheme (laland)")
d["KPlugin"] = k
json.dump(d, open(p, "w"), indent=4)
PY
# square frames klassy-dark doesn't ship (dialogs, line edits, list items), so they'd fall back to
# Breeze's rounded ones. Sources: templates/plasma/, generated by scripts/plasma_svgs.py.
src_svgs="$(cd "$(dirname "$0")/.." && pwd)/templates/plasma"
(cd "$src_svgs" && find . -name '*.svg') | while read -r rel; do
    mkdir -p "$dst/$(dirname "$rel")"
    gzip -c "$src_svgs/$rel" > "$dst/${rel%.svg}.svgz"
done
# Plasma caches rendered theme SVGs; drop laland's cache so the new frame is picked up
rm -f "$HOME/.cache/plasma_theme_laland.kcache"
plasma-apply-desktoptheme laland
